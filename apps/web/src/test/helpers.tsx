export interface Call {
  method: string;
  path: string;
  query: URLSearchParams;
  body: unknown;
  headers: Record<string, string>;
}

type Reply = { status?: number; body?: unknown } | ((call: Call) => { status?: number; body?: unknown });

/**
 * Stub fetch with replies keyed by "METHOD /path" (path after /api/v1, no
 * query).  Unmatched requests fail the test loudly with a 599.
 */
export function mockApi(routes: Record<string, Reply>) {
  const calls: Call[] = [];
  const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = new URL(String(input), "http://localhost");
    const call: Call = {
      method: init?.method ?? "GET",
      path: url.pathname.replace(/^\/api\/v1/, ""),
      query: url.searchParams,
      body: init?.body ? JSON.parse(String(init.body)) : undefined,
      headers: (init?.headers as Record<string, string>) ?? {},
    };
    calls.push(call);
    const route = routes[`${call.method} ${call.path}`];
    if (!route) return new Response(JSON.stringify({ detail: `unmocked ${call.method} ${call.path}` }), { status: 599 });
    const reply = typeof route === "function" ? route(call) : route;
    return new Response(reply.body === undefined ? "" : JSON.stringify(reply.body), { status: reply.status ?? 200 });
  });
  vi.stubGlobal("fetch", fetchMock);
  return { calls, fetchMock, callsTo: (method: string, path: string) => calls.filter((c) => c.method === method && c.path === path) };
}

