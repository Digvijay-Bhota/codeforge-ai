import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, describe, expect, it } from "vitest";
import type { PublicationArtifact, TaskDetail } from "../api/types";
import { artifact, DIGEST, mockApi, renderApp, signedIn, taskDetail, USER } from "../test/helpers";
import { activity } from "../test/helpers";
import { decisionState } from "./PublicationReview";

const TASK = "11111111-aaaa-bbbb-cccc-000000000001";
const PATH = `/tasks/${TASK}`;

interface Setup {
  task?: Partial<TaskDetail>;
  publication?: Partial<PublicationArtifact> | null;
  diff?: unknown;
  approve?: { status?: number; body?: unknown };
  reject?: { status?: number; body?: unknown };
}

function setup({ task = {}, publication = {}, diff = null, approve, reject }: Setup = {}) {
  let current = taskDetail(task);
  let currentPublication = publication === null ? null : artifact(publication);
  const api = mockApi({
    "GET /auth/me": { body: USER },
    [`GET ${PATH}`]: () => ({ body: current }),
    [`GET ${PATH}/activity`]: { body: activity() },
    [`GET ${PATH}/publication`]: () =>
      currentPublication ? { body: currentPublication } : { status: 404, body: { detail: "No generated changes" } },
    [`GET ${PATH}/diff`]: diff ? { body: diff } : { status: 404 },
    [`POST ${PATH}/publication/approve`]: () => {
      if (approve && (approve.status ?? 200) >= 400) return approve;
      current = { ...current, status: "PUBLISHING" };
      currentPublication = currentPublication && { ...currentPublication, approval_status: "APPROVED", approved_by: "ada" };
      return { body: { task_id: TASK, status: "PUBLISHING", message: "Publication approved and queued" } };
    },
    [`POST ${PATH}/publication/reject`]: () => {
      if (reject && (reject.status ?? 200) >= 400) return reject;
      current = { ...current, status: "CANCELLED" };
      currentPublication = currentPublication && { ...currentPublication, approval_status: "REJECTED" };
      return { body: { task_id: TASK, status: "CANCELLED", message: "Publication rejected; nothing was pushed" } };
    },
  });
  renderApp(PATH);
  return api;
}

async function openAllFiles() {
  const files = await screen.findByRole("list", { name: "Changed files" });
  for (const button of within(files).getAllByRole("button")) await userEvent.click(button);
}

beforeEach(() => signedIn());

describe("publication review", () => {
  it("shows exactly what will be published", async () => {
    setup();
    expect(await screen.findByRole("heading", { name: "Generated changes" })).toBeInTheDocument();
    expect(screen.getByText("Awaiting review", { selector: ".review .badge" })).toBeInTheDocument();
    expect(screen.getByText("Fix the widget total calculation", { selector: ".pr-title" })).toBeInTheDocument();
    expect(screen.getByLabelText("Pull request description")).toHaveTextContent("Generated by CodeForge.");
    expect(screen.getByLabelText("Commit message")).toHaveTextContent("Fix widget totals");
    expect(screen.getByLabelText("Content of src/widget.py")).toHaveTextContent("return 42");
    expect(screen.getByText(/Expires in/)).toBeInTheDocument();
  });

  it("renders repository content and agent text as text, never markup", async () => {
    const payload = '<img src=x onerror="window.__pwned=1"><script>window.__pwned=1</script>';
    setup({
      publication: {
        pull_request_title: payload,
        pull_request_body: payload,
        files: [{ path: "index.html", action: "write", content: payload }],
      },
    });
    const code = await screen.findByLabelText("Content of index.html");
    expect(code).toHaveTextContent(payload);
    expect(screen.getByLabelText("Pull request description")).toHaveTextContent(payload);
    expect(document.querySelector("img[src='x']")).toBeNull();
    expect(document.querySelector("main script")).toBeNull();
    expect((window as unknown as { __pwned?: number }).__pwned).toBeUndefined();
  });

  it("enables approval only after every file has been opened", async () => {
    setup();
    const approve = await screen.findByRole("button", { name: "Approve and publish" });
    expect(approve).toBeDisabled();
    expect(screen.getByText(/Open every file to enable approval \(1 of 2 reviewed\)/)).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /src\/legacy\.py/ }));
    expect(screen.getByText("This file will be deleted.")).toBeInTheDocument();
    expect(approve).toBeEnabled();
  });

  it("approves exactly the reviewed digest, with the comment", async () => {
    const api = setup();
    await openAllFiles();
    await userEvent.click(screen.getByRole("button", { name: "Approve and publish" }));
    const dialog = screen.getByRole("dialog", { name: "Approve and publish these changes?" });
    expect(within(dialog).getByText(DIGEST)).toBeInTheDocument();
    expect(within(dialog).getByText(`codeforge/task-${TASK}`)).toBeInTheDocument();
    await userEvent.type(within(dialog).getByLabelText("Comment (optional)"), "Looks right");
    await userEvent.click(within(dialog).getByRole("button", { name: "Approve and publish" }));

    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    const [call] = api.callsTo("POST", `${PATH}/publication/approve`);
    expect(call?.body).toEqual({ artifact_digest: DIGEST, comment: "Looks right" });
    expect(await screen.findByText("Publication approved and queued")).toBeInTheDocument();
    expect(await screen.findByText("Approved by ada. Publishing…")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Approve and publish" })).toBeNull();
  });

  it("keeps the dialog open and explains a refusal", async () => {
    setup({ approve: { status: 403, body: { detail: "Write permission required for repository acme/widgets" } } });
    await openAllFiles();
    await userEvent.click(screen.getByRole("button", { name: "Approve and publish" }));
    const dialog = screen.getByRole("dialog");
    await userEvent.click(within(dialog).getByRole("button", { name: "Approve and publish" }));
    expect(await within(dialog).findByRole("alert")).toHaveTextContent("Write permission required");
    expect(within(dialog).getByRole("button", { name: "Approve and publish" })).toBeEnabled();
  });

  it("rejects with a reason", async () => {
    const api = setup();
    await userEvent.click(await screen.findByRole("button", { name: "Reject" }));
    const dialog = screen.getByRole("dialog", { name: "Reject these changes?" });
    await userEvent.type(within(dialog).getByLabelText("Reason (optional)"), "Wrong approach");
    await userEvent.click(within(dialog).getByRole("button", { name: "Reject changes" }));
    await waitFor(() => expect(api.callsTo("POST", `${PATH}/publication/reject`)).toHaveLength(1));
    expect(api.callsTo("POST", `${PATH}/publication/reject`)[0]?.body).toEqual({ reason: "Wrong approach" });
    expect(await screen.findByText("Publication rejected; nothing was pushed")).toBeInTheDocument();
  });

  it("closes the dialog with Escape and returns focus", async () => {
    setup();
    const reject = await screen.findByRole("button", { name: "Reject" });
    await userEvent.click(reject);
    expect(screen.getByRole("dialog")).toBeInTheDocument();
    await userEvent.keyboard("{Escape}");
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(reject).toHaveFocus();
  });

  it("offers no decision once the changes are published, and links only to GitHub", async () => {
    setup({
      task: { status: "COMPLETED" },
      publication: { approval_status: "APPROVED", published: true, pull_request_url: "https://github.com/acme/widgets/pull/7" },
    });
    expect(await screen.findByRole("link", { name: /view pull request/i })).toHaveAttribute(
      "href",
      "https://github.com/acme/widgets/pull/7",
    );
    expect(screen.queryByRole("button", { name: "Approve and publish" })).toBeNull();
    expect(screen.queryByRole("button", { name: "Reject" })).toBeNull();
  });

  it("does not link to a pull request URL outside GitHub", async () => {
    setup({
      task: { status: "COMPLETED" },
      publication: { approval_status: "APPROVED", published: true, pull_request_url: "https://evil.example/pull/7" },
    });
    await screen.findByText("Published", { selector: ".review .badge" });
    expect(screen.queryByRole("link", { name: /view pull request/i })).toBeNull();
  });

  it("shows the generation diff, labelled as outside the approval", async () => {
    setup({
      diff: {
        task_id: TASK,
        files_changed_count: 1,
        additions: 1,
        deletions: 1,
        files: [{ path: "src/widget.py", status: "modified", additions: 1, deletions: 1, patch: "@@ -1 +1 @@\n-    return 41\n+    return 42" }],
      },
    });
    const diff = await screen.findByLabelText("Diff of src/widget.py");
    expect(diff).toHaveTextContent("+    return 42", { normalizeWhitespace: false });
    expect(screen.getByText(/Approval covers the exact content, not this diff/)).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: "Exact content" }));
    expect(screen.getByLabelText("Content of src/widget.py")).toBeInTheDocument();
  });

  it("is absent for tasks that captured no changes", async () => {
    setup({ task: { status: "FAILED", failure_reason: "Tests failed" }, publication: null });
    expect(await screen.findByText("Tests failed")).toBeInTheDocument();
    await waitFor(() => expect(screen.queryByText("Loading generated changes…")).toBeNull());
    expect(screen.queryByRole("heading", { name: "Generated changes" })).toBeNull();
  });
});

describe("decisionState", () => {
  const now = Date.parse("2026-10-21T12:00:00Z");

  it("allows a decision only while pending, in review and unexpired", () => {
    const pending = artifact({ expires_at: "2026-10-21T13:00:00Z" });
    expect(decisionState(pending, "WAITING_PUBLICATION", now).canDecide).toBe(true);
    expect(decisionState(pending, "PUBLISHING", now).canDecide).toBe(false);
    expect(decisionState(artifact({ expires_at: "2026-10-21T11:59:00Z" }), "WAITING_PUBLICATION", now)).toMatchObject({
      label: "Expired",
      canDecide: false,
    });
    for (const approval_status of ["APPROVED", "REJECTED", "EXPIRED", null]) {
      expect(decisionState(artifact({ approval_status }), "WAITING_PUBLICATION", now).canDecide).toBe(false);
    }
    expect(decisionState(artifact({ published: true }), "COMPLETED", now).label).toBe("Published");
  });
});
